import assert from 'node:assert/strict';
import {getChangelog, validateEdition, editionCacheControl} from '../lib/changelog.mjs';
const news = {articles:Array.from({length:8}, (_,i) => ({title:`Community restores forest ${i}`,url:`https://example.org/${i}`,date:'2026-09-19',publisher:'Example',category:'Positive news'})),checkedAt:1,unavailable:[],stale:[]};
const entry = {sourceId:2,title:'Forest restored',note:'The community restored a forest. More room for the neighbours with wings.',kind:'Improved'};
assert.equal(validateEdition({entries:[{...entry,url:'https://wrong.example'}]},news.articles)[0].url,news.articles[2].url);
for (const entries of [[{...entry,sourceId:99}],[entry,entry],[{...entry,note:''}],[{...entry,kind:'Invented'}],Array(7).fill(entry)]) assert.throws(()=>validateEdition({entries},news.articles));
assert.deepEqual(validateEdition({entries:[]},news.articles),[]);
let calls = 0;
const fetcher = async (url, options) => {
 calls++;
 assert.equal(options.headers.Authorization,'Bearer test');
 assert.ok(!url.includes('test'));
 const body=JSON.parse(options.body);
 assert.ok(body.messages[0].content.includes('Never joke about suffering'));
 const candidates=JSON.parse(body.messages[1].content).candidates;
 assert.equal(candidates.length,8);
 assert.equal(candidates[0].date,'2026-09-19');
 return Response.json({choices:[{finish_reason:'stop',message:{content:JSON.stringify({entries:[entry]})}}]});
};
const opts = {apiKey:'test',fetcher,now:1_000_000};
assert.equal((await getChangelog(news)).editorial,'unconfigured');
const [first,second] = await Promise.all([getChangelog(news,opts),getChangelog(news,opts)]);
assert.equal(calls,1); assert.deepEqual(first,second); assert.equal(first.editorial,'generated');
assert.equal(first.articles[0].originalTitle,news.articles[2].title);
assert.equal(editionCacheControl(first),'public, s-maxage=900, stale-while-revalidate=3600');
assert.equal(editionCacheControl({...first,editorial:'unavailable'}),'public, s-maxage=60, stale-while-revalidate=60');
assert.equal(editionCacheControl({...first,articles:[]}),'no-store');
await getChangelog(news,{...opts,now:opts.now+1000}); assert.equal(calls,1);
const failed = {...opts,now:opts.now+3_600_001,fetcher:async()=>{calls++;return new Response('',{status:429});}};
assert.equal((await getChangelog(news,failed)).editorial,'cached');
assert.deepEqual((await getChangelog(news,failed)).articles,first.articles); assert.equal(calls,2);
const malformed = {...opts,now:failed.now+900_001,fetcher:async()=>Response.json({candidates:[{finishReason:'STOP',content:{parts:[{text:'not json'}]}}]})};
assert.equal((await getChangelog(news,malformed)).editorial,'cached');
console.log('Groq source mapping, validation, caching/coalescing, missing key and failure fallback pass.');
for (const kind of ['Added','Removed','Changed','Patched']) assert.equal(validateEdition({entries:[{...entry,kind}]},news.articles)[0].kind,kind);

const {getChangelog:coldStart}=await import('../lib/changelog.mjs?cold-outage');
const outage=await coldStart(news,{apiKey:'test',fetcher:async()=>new Response('',{status:429}),now:opts.now});
assert.deepEqual(outage.articles,[]);
assert.equal(outage.editorial,'unavailable');
const expired=await getChangelog(news,{...failed,now:opts.now+24*60*60_000+1});
assert.deepEqual(expired.articles,[]);
const {getChangelog:filtered}=await import('../lib/changelog.mjs?filter');
const mixed={...news,articles:[...news.articles,{...news.articles[0],title:'Election dispute',category:'World'}]};
assert.equal((await filtered(mixed,opts)).editorial,'generated'); // Mock asserts only the eight relevant candidates reach Groq.
console.log('Raw headlines excluded on cold outages, curated fallback expires, and unrelated categories never reach Groq.');
